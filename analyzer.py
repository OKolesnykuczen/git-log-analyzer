import sys
from datetime import datetime


def прочитати_лог(імя_файлу):
    try:
        with open(імя_файлу, "r", encoding="utf-8") as файл:
            return файл.readlines()
    except FileNotFoundError:
        print(f"Помилка: файл '{імя_файлу}' не знайдено.")
        return []


def розібрати_коміт(рядок):
    частини = рядок.strip().split("|")

    if len(частини) != 4:
        return None

    хеш, автор, дата, повідомлення = частини

    try:
        дата = datetime.strptime(дата, "%a %b %d %H:%M:%S %Y %z")
    except ValueError:
        return None

    return {
        "хеш": хеш,
        "автор": автор,
        "дата": дата,
        "повідомлення": повідомлення
    }


def обробити_лог(рядки):
    коміти = []

    for рядок in рядки:
        if not рядок.strip():
            continue

        коміт = розібрати_коміт(рядок)

        if коміт is not None:
            коміти.append(коміт)
        else:
            print("Попередження: пропущено рядок неправильного формату.")

    return коміти


def побудувати_звіт(коміти, назва_гілки):
    if not коміти:
        return f"\nГілка: {назва_гілки}\nНемає комітів."

    автори = set(коміт["автор"] for коміт in коміти)
    коміти_за_датою = sorted(коміти, key=lambda коміт: коміт["дата"])

    перший = коміти_за_датою[0]
    останній = коміти_за_датою[-1]

    звіт = [
        f"\nГілка: {назва_гілки}",
        f"Кількість комітів: {len(коміти)}",
        f"Кількість авторів: {len(автори)}",
        f"Перший коміт: {перший['повідомлення']}",
        f"Останній коміт: {останній['повідомлення']}"
    ]

    return "\n".join(звіт)


def показати_коміти(коміти):
    if not коміти:
        print("Комітів немає.")
        return

    print("\nСписок комітів:")

    for коміт in коміти:
        дата = коміт["дата"].strftime("%Y-%m-%d")
        print(f"{дата} | {коміт['автор']} | {коміт['повідомлення']}")


def статистика_авторів(коміти):
    автори = {}

    for коміт in коміти:
        автор = коміт["автор"]
        автори[автор] = автори.get(автор, 0) + 1

    print("\nСтатистика авторів:")

    for автор, кількість in автори.items():
        print(f"{автор}: {кількість} комітів")


def main():
    if len(sys.argv) < 2:
        print("Помилка: вкажіть ім'я файлу з логом.")
        return

    імя_файлу = sys.argv[1]
    рядки = прочитати_лог(імя_файлу)

    if not рядки:
        return

    назва_гілки = рядки[0].strip()
    коміти = обробити_лог(рядки[1:])

    print(побудувати_звіт(коміти, назва_гілки))
    показати_коміти(коміти)
    статистика_авторів(коміти)


if __name__ == "__main__":
    main()